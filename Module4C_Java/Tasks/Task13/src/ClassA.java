public class ClassA {

        // Constructor 1
        public ClassA() {
            System.out.println("Constructor with no parameter");
        }

        // Constructor 2
        public ClassA(String name) {
            System.out.println("Name: " + name);
        }

        // Constructor 3
        public ClassA(String name, int age) {
            System.out.println("Name: " + name + ", Age: " + age);
        }
    }

