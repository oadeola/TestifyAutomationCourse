public class JavaDataTypes {
    static void main(String[] args) {

        {
            byte age = 115;
            short shortMoney = -31_555;
            long longMoney = 999911122;
            int intMoney = -909991234;
            float area1 = 499222.11f;
            double area2 = 12344444.5622;

            System.out.println("Age: " + age);
            System.out.println("ShortMoney: " + shortMoney);
            System.out.println("LongMoney: " + longMoney);
            System.out.println("IntMoney: " + intMoney);
            System.out.println("Area1: " + area1);
            System.out.println("Area2: " + area2);
        }
    }
}