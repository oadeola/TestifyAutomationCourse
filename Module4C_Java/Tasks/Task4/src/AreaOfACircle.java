//Task 4 - Area Of A Circle
public class AreaOfACircle {
    static void main(String[] args){
        double pi = 3.14;
        double radius1 = 12.7;
        double radius2 = 12.7;

        //area of a circle
        double area = (pi * radius1 * radius2);
        System.out.println("Area of a circle is: " + area +"meters");
    }
}
